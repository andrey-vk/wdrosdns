// Regenerates public-suffix-list.js from the Public Suffix List.
//
//   node scripts/update-public-suffix-list.mjs
//   node scripts/update-public-suffix-list.mjs --from /path/to/public_suffix_list.dat
//
// The generated module is committed so the extension never needs network access
// at runtime. Rules are stored punycode-encoded, because hostnames the extension
// sees come from URL.hostname and are already punycode.

import { readFile, writeFile } from "node:fs/promises";

const SOURCE_URL = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUTPUT = "public-suffix-list.js";

function argValue(name) {
  const idx = process.argv.indexOf(name);
  return idx >= 0 ? process.argv[idx + 1] : null;
}

async function readSource() {
  const from = argValue("--from");
  if (from) return await readFile(from, "utf8");

  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`${SOURCE_URL} responded ${res.status}`);
  return await res.text();
}

// "рф" -> "xn--p1ai"; a leading "*"/"!" is not part of a DNS label.
function toPunycode(rule) {
  const prefix = rule.startsWith("!") ? "!" : "";
  const body = prefix ? rule.slice(1) : rule;

  const labels = body.split(".").map(label => {
    if (label === "*" || /^[\x21-\x7e]+$/.test(label)) return label;
    return new URL(`http://${label}.invalid`).hostname.replace(/\.invalid$/, "");
  });

  return prefix + labels.join(".");
}

function parseRules(text) {
  const rules = [];
  const seen = new Set();

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("//")) continue;

    const rule = toPunycode(line.split(/\s/)[0].toLowerCase());
    if (!rule || seen.has(rule)) continue;

    seen.add(rule);
    rules.push(rule);
  }

  return rules;
}

async function main() {
  const rules = parseRules(await readSource());
  if (rules.length < 5000) {
    throw new Error(`only ${rules.length} rules parsed, source looks truncated`);
  }

  const wildcards = rules.filter(r => r.startsWith("*.")).length;
  const exceptions = rules.filter(r => r.startsWith("!")).length;

  const module = `// Generated by scripts/update-public-suffix-list.mjs — do not edit by hand.
// Source: ${SOURCE_URL} (Mozilla Public License 2.0)
// Rules: ${rules.length} (${wildcards} wildcard, ${exceptions} exception), punycode-encoded.

export const PUBLIC_SUFFIX_RULES = \`${rules.join("\n")}\`;
`;

  await writeFile(OUTPUT, module, "utf8");
  console.log(`✓ ${OUTPUT}: ${rules.length} rules (${wildcards} wildcard, ${exceptions} exception)`);
}

main().catch(err => {
  console.error(`✗ ${err.message}`);
  process.exitCode = 1;
});
